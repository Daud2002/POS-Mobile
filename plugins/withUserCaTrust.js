/**
 * Expo config plugin: let the Android app trust certificate authorities the
 * user installed on the phone, not only the system ones.
 *
 * Why: a shop's store server (the TapnTrade server on the cashier PC) serves
 * HTTPS with a certificate signed by that shop's own CA, which staff install
 * once per phone. Since Android 7 apps ignore user-installed CAs unless their
 * network security config opts in, so without this the app could never reach
 * the store server, however the phone is set up.
 *
 * `/android` is generated (and gitignored), so this plugin is the source of
 * truth: `expo prebuild` / `expo run:android` re-apply it every time.
 *
 * Debug builds get their own copy of the file that also allows plain HTTP.
 * Once an app has a network security config, Android ignores the
 * `usesCleartextTraffic="true"` that Expo's debug manifests rely on for
 * reaching Metro, so without that copy the dev client could not load the
 * bundle. Build-type resources override `main`, so release keeps the default
 * (no cleartext).
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RESOURCE_NAME = 'network_security_config';

const TRUST_ANCHORS = [
  '    <trust-anchors>',
  '      <certificates src="system" />',
  '      <certificates src="user" />',
  '    </trust-anchors>',
];

function networkSecurityConfigXml({ cleartext }) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withUserCaTrust.js. Edit the plugin, not this file. -->',
    '<network-security-config>',
    cleartext ? '  <base-config cleartextTrafficPermitted="true">' : '  <base-config>',
    ...TRUST_ANCHORS,
    '  </base-config>',
    '</network-security-config>',
    '',
  ].join('\n');
}

/** Writes the release file under `main` and the cleartext-allowing ones under the debug build types. */
function writeNetworkSecurityConfigs(androidRoot) {
  const variants = [
    { sourceSet: 'main', cleartext: false },
    { sourceSet: 'debug', cleartext: true },
    { sourceSet: 'debugOptimized', cleartext: true },
  ];
  for (const { sourceSet, cleartext } of variants) {
    const dir = path.join(androidRoot, 'app', 'src', sourceSet, 'res', 'xml');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, `${RESOURCE_NAME}.xml`), networkSecurityConfigXml({ cleartext }));
  }
}

function setNetworkSecurityConfig(androidManifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  application.$['android:networkSecurityConfig'] = `@xml/${RESOURCE_NAME}`;
  return androidManifest;
}

const withUserCaTrust = (config) => {
  config = withAndroidManifest(config, (cfg) => {
    cfg.modResults = setNetworkSecurityConfig(cfg.modResults);
    return cfg;
  });

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      writeNetworkSecurityConfigs(cfg.modRequest.platformProjectRoot);
      return cfg;
    },
  ]);

  return config;
};

module.exports = withUserCaTrust;
module.exports.networkSecurityConfigXml = networkSecurityConfigXml;
module.exports.writeNetworkSecurityConfigs = writeNetworkSecurityConfigs;
module.exports.setNetworkSecurityConfig = setNetworkSecurityConfig;
